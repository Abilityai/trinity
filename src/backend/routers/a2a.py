"""
A2A (Agent-to-Agent) protocol endpoints (#737 card; ent#157 inbound server;
#736 outbound calls).

Three surfaces live here:

1. `GET /api/agents/{name}/a2a/agent-card` (#737) — the authenticated
   per-agent Agent Card. External orchestrators (AWS Bedrock, Azure
   Copilot, Google ADK) consume it to discover what the agent can do
   without knowing Trinity's internal API.
2. The **inbound server** (ent#157) on the prefix-less
   `a2a_server_router`: a public `GET /a2a/{name}/.well-known/agent-card.json`
   plus the JSON-RPC task endpoint `POST /a2a/{name}`. Exposure is opt-in
   per agent (`agent_ownership.a2a_exposed`, default OFF) and everything
   non-exposed / inaccessible answers a uniform 404 (Invariant #8), so the
   public surface is not an enumeration oracle.
3. The **outbound client** (#736): `POST /api/agents/{name}/a2a/call` and
   `POST /api/agents/{name}/a2a/task`, which let a Trinity agent task an
   EXTERNAL A2A agent. The target is never supplied by the caller — it is a
   reference into an operator-registered endpoint list, resolved server-side —
   and the orchestration lives in `services/a2a_outbound_service.py`; the
   routes below are auth, the HTTP error map, and the audit row.

The card is generated by the backend from the agent's `template.yaml`
+ ownership metadata — no agent-server changes required. The agent
container doesn't need to be running for a stopped agent's card to
be served; we fall back to the metadata carried on the Docker
container's labels, which survive `docker stop`.
"""

