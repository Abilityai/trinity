def _rpc_error(rpc_id: Any, code: int, message: str, data: Any = None) -> JSONResponse:
    """A JSON-RPC 2.0 error envelope. Transport stays HTTP 200 — the error is
    carried in the body (auth failures are the exception: those are HTTP 401 via
    the dependency, before we ever parse an envelope)."""
    err: Dict[str, Any] = {"code": code, "message": message}
    if data is not None:
        err["data"] = data
    return JSONResponse({"jsonrpc": "2.0", "id": rpc_id, "error": err})


def _rpc_result(rpc_id: Any, result: Any) -> JSONResponse:
    return JSONResponse({"jsonrpc": "2.0", "id": rpc_id, "result": result})


def _exec_field(row: Any, name: str) -> Any:
    """Read a field from an execution row that may be a ScheduleExecution model
    (attribute) OR a dict (mapping) — `db.get_execution` returns the former."""
    if isinstance(row, dict):
        return row.get(name)
    return getattr(row, name, None)


def _text_from_message(message: Dict[str, Any]) -> str:
    """Concatenate the text parts of an A2A message (v0.3 part kind='text')."""
    parts = message.get("parts") if isinstance(message, dict) else None
    if not isinstance(parts, list):
        return ""
    out = []
    for p in parts:
        if isinstance(p, dict) and p.get("kind") == "text" and isinstance(p.get("text"), str):
            out.append(p["text"])
    return "\n".join(out).strip()


def _task_object(execution_id: str, state: str, *, text: Optional[str] = None,
                 context_id: Optional[str] = None, error: Optional[str] = None) -> Dict[str, Any]:
    """Build an A2A Task object. `state`: submitted|working|completed|failed|canceled."""
    task: Dict[str, Any] = {
        "id": execution_id,
        "contextId": context_id or execution_id,
        "kind": "task",
        "status": {"state": state},
    }
    if text is not None:
        task["artifacts"] = [{
            "artifactId": uuid.uuid4().hex,
            "parts": [{"kind": "text", "text": text}],
        }]
    if error is not None:
        task["status"]["message"] = {
            "role": "agent",
            "parts": [{"kind": "text", "text": error}],
            "messageId": uuid.uuid4().hex,
        }
    return task


def _a2a_state_for(status: str) -> str:
    """Map a Trinity TaskExecutionStatus to an A2A task state.

    A cancelled execution is `canceled`, not `failed` — the A2A spec treats them
    as distinct terminal states and a caller that cancelled its own task should
    not be told the task errored.
    """
    return {"success": "completed", "cancelled": "canceled"}.get(status, "failed")


def _a2a_idem_scope(agent_name: str, current_user: Optional[User],
                    aauth: Optional["aauth_verifier.VerifiedAgent"] = None) -> str:
    """Dedup scope for an inbound A2A `messageId`: per (agent, caller principal).

    `messageId` is a **peer-controlled** protocol field that A2A SDKs generate
    automatically, and the spec only requires uniqueness *per client* — two
    callers legitimately collide on `"req-1"`. Scoping on the agent alone would
    make one caller's `messageId` resolve to another caller's stored snapshot,
    which carries the agent's full response text: caller B would receive caller
    A's output and B's own task would silently never run.

    Keying the scope on the caller principal gives every caller a private
    `messageId` namespace, so a collision can only ever replay the caller's own
    prior result. `mcp_key_id` is preferred over `username` because agent-scoped
    keys all resolve to the same owner user — the key id is what distinguishes
    two agents calling on the same owner's behalf.
    """
    if aauth is not None:
        # ent#623: an AAuth caller's namespace is its verified agent identity.
        return f"a2a:{agent_name}:aauth|{aauth.identity}"
    principal = (
        getattr(current_user, "mcp_key_id", None)
        or getattr(current_user, "username", None)
        or "anonymous"
    )
    return f"a2a:{agent_name}:{principal}"


async def _serve_card(agent_name: str, request: Request) -> Optional[Dict[str, Any]]:
    """Build the honest A2A card for an EXPOSED agent, or None (→ uniform 404).

    Uniform 404 for non-exposed / non-existent so the public surface is not an
    enumeration oracle. Exposure can only be set by the entitled enterprise
    setter, so in an OSS-only / unentitled build every agent is non-exposed and
    this always returns None (routes 404) — safe by default.
    """
    if not db.get_a2a_exposed(agent_name):
        return None
    container = get_agent_container(agent_name)
    if not container:
        return None
    template_data = await _fetch_template_data(agent_name, container)
    return _card_with_exposed_skills(
        agent_name=agent_name,
        template_data=template_data,
        base_url=_base_url_from_request(request),
    )


@a2a_server_router.get("/a2a/{agent_name}/.well-known/agent-card.json")
async def a2a_well_known_card(agent_name: str, request: Request):
    """Public (unauthenticated) A2A discovery card for an exposed agent.

    404 (uniform) when the agent is non-existent or not A2A-exposed. The card's
    `url` points at `POST /a2a/{name}` (the JSON-RPC task endpoint).

    Per-IP rate limited BEFORE any DB/Docker/agent work — the expensive part of
    serving a card is exactly what an unauthenticated flood would amplify.
    Trusted-proxy aware (so X-Forwarded-For can't be spoofed past it) and
    fail-open, per the shared limiter's contract.
    """
    rate_limiter.enforce(
        f"a2a_card_ip:{_get_client_ip(request)}",
        A2A_CARD_RATE_LIMIT,
        A2A_CARD_RATE_WINDOW,
        detail="Too many A2A card requests from this address.",
    )
    card = await _serve_card(agent_name, request)
    if card is None:
        raise HTTPException(status_code=404, detail="Not found")
    return card


def _authorize_inbound(current_user: User, agent_name: str) -> None:
    """Exposure + access + allow-list gate for an inbound A2A task. Raises
    HTTPException(404) for non-exposed/inaccessible (uniform — no enumeration),
    HTTPException(403) when the caller is off the per-agent allow-list."""
    if not db.get_a2a_exposed(agent_name):
        raise HTTPException(status_code=404, detail="Not found")
    if not db.can_user_access_agent(current_user.username, agent_name):
        raise HTTPException(status_code=404, detail="Not found")
    caller_identity = getattr(current_user, "email", None) or current_user.username
    if not a2a_gate.check_inbound_allowed(agent_name, caller_identity):
        raise HTTPException(status_code=403, detail="Caller not on the agent's A2A inbound allow-list")


async def _run_a2a_task(agent_name: str, text: str, current_user: User):
    """Bridge one inbound A2A message into the Trinity execution stack.

    #2524: goes through `dispatch_and_await_terminal`, not `execute_task`
    directly. Both callers below consume `result.status` / `result.response` to
    build the JSON-RPC artifact they hand a remote caller, and under
    `PULL_MODE_PILOT_AGENTS` a dispatch returns `QUEUED` as soon as the row is on
    the durable queue — the turn runs later, in the agent's worker. The adapter
    waits out that queue and rebuilds the result from the row, so the artifact is
    the same whether the turn ran inside this await or somewhere else. That is
    what lets `a2a` join `pull_pilot.PULL_REACHABLE_TRIGGERS` without touching the
    JSON-RPC contract, which is one request / one artifact and has no receipt to
    hand back.
    """
    return await dispatch_and_await_terminal(
        agent_name=agent_name,
        message=text,
        triggered_by="a2a",
        source_user_id=getattr(current_user, "id", None),
        source_user_email=getattr(current_user, "email", None),
        source_mcp_key_id=getattr(current_user, "mcp_key_id", None),
    )


@a2a_server_router.post(_A2A_RPC_PATH)
async def a2a_jsonrpc(
    agent_name: str,
    request: Request,
    current_user: User = Depends(get_current_user),
):
    """A2A JSON-RPC 2.0 task endpoint. Bearer = a Trinity MCP API key (validated
    by `get_current_user` — fail-closed 401). Methods: message/send,
    message/stream (SSE), tasks/get, tasks/cancel.

    An AAuth-signed request (ent#623) never reaches this function — see
    `_A2AServerRoute` and `_a2a_aauth_jsonrpc`; both share `_dispatch_jsonrpc`."""
    _authorize_inbound(current_user, agent_name)

    # Cap before parsing — an uncapped await request.json() lets one caller pin
    # memory. nginx caps at 25m, but :8000 may be reachable directly.
    raw = await request.body()
    return await _dispatch_jsonrpc(agent_name, request, raw, current_user=current_user)


