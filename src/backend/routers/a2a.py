#: What a bearer-less 401 advertises while AAuth is live.
_AAUTH_CHALLENGE_HEADERS = {
    "Accept-Signature": "sig=(" + " ".join(
        f'"{c}"' for c in aauth_httpsig.components_for("POST")
    ) + ")",
    "Accept-Signature-Scheme": "jwt",
    "AAuth-Requirement": "requirement=agent-token",
}

A2A_AAUTH_RATE_LIMIT = 60     # signed task requests per IP
A2A_AAUTH_RATE_WINDOW = 60


def _aauth_problem(exc: "aauth_verifier.AAuthError") -> JSONResponse:
    """RFC 9457 problem details; `Signature-Error` is the interoperable carrier."""
    headers = {}
    if exc.status == 401:
        headers["Signature-Error"] = f"error={exc.code}"
        if exc.code in ("invalid_input", "unsupported_scheme"):
            headers["Accept-Signature"] = _AAUTH_CHALLENGE_HEADERS["Accept-Signature"]
            headers["Accept-Signature-Scheme"] = "jwt"
    return JSONResponse(
        status_code=exc.status,
        media_type="application/problem+json",
        headers=headers,
        content={
            "type": f"urn:ietf:params:sig-error:{exc.code}",
            "error": exc.code,
            "detail": exc.detail,
        },
    )


def _aauth_request_facts(request: Request) -> "aauth_verifier.InboundRequest":
    raw_path = request.scope.get("raw_path") or request.url.path.encode("utf-8")
    if isinstance(raw_path, bytes):
        raw_path = raw_path.decode("latin-1")
    headers: Dict[str, str] = {}
    for name, value in request.headers.items():   # repeated fields joined, RFC 9110 §5.3
        headers[name] = f"{headers[name]}, {value}" if name in headers else value
    declared = request.headers.get("content-length")
    return aauth_verifier.InboundRequest(
        method=request.method,
        raw_path=raw_path.split("?", 1)[0],
        headers=headers,
        content_length=int(declared) if declared and declared.isdigit() else None,
    )


async def _a2a_aauth_jsonrpc(request: Request, issuer: str):
    """`POST /a2a/{name}` for a caller authenticated by AAuth agent identity.

    Refused before the body is parsed as JSON-RPC, like a bearer failure. The
    caller never becomes a Trinity `User`: access is exposure + an EXPLICIT
    allow-list entry for its verified identity (fail-closed), and no owner role
    travels with it.
    """
    agent_name = request.path_params["agent_name"]
    caller_ip = request.client.host if request.client else None

    # Limit first: everything below costs at least a DB read, and the caller is
    # still an unauthenticated stranger here.
    try:
        rate_limiter.enforce(
            f"a2a_aauth_ip:{_get_client_ip(request)}",
            A2A_AAUTH_RATE_LIMIT,
            A2A_AAUTH_RATE_WINDOW,
            detail="Too many signed A2A requests from this address.",
        )
    except HTTPException as exc:
        return JSONResponse(status_code=exc.status_code, content={"detail": exc.detail},
                            headers=exc.headers)
    if not db.get_a2a_exposed(agent_name):
        return JSONResponse(status_code=404, content={"detail": "Not found"})

    identities = a2a_gate.explicit_inbound_identities(agent_name)

    async def _read_body() -> bytes:
        chunks, total = [], 0
        async for chunk in request.stream():
            total += len(chunk)
            if total > _MAX_RPC_BODY_BYTES:
                raise aauth_verifier.AAuthError("invalid_input", "request body too large",
                                                status=413, trusted=True)
            chunks.append(chunk)
        return b"".join(chunks)

    try:
        verified, raw = await aauth_verifier.verify_request(
            _aauth_request_facts(request),
            expected_authority=aauth_config.issuer_host(issuer),
            trusted_identities=identities or [],
            read_body=_read_body,
            max_body_bytes=_MAX_RPC_BODY_BYTES,
        )
    except aauth_verifier.AAuthError as exc:
        # Only refusals past the trusted-issuer pre-gate are audited: before it,
        # the caller is an unauthenticated stranger and an audit row per request
        # would hand them the audit table.
        logger.info("[aauth] refused signed A2A request for %s: %s (%s)",
                    agent_name, exc.code, exc.identity or "unidentified")
        if exc.trusted:
            await platform_audit_service.log(
                event_type=AuditEventType.AUTHENTICATION, event_action="a2a_aauth_refused",
                source="a2a", actor_external_id=exc.identity, actor_ip=caller_ip,
                target_type="agent", target_id=agent_name, endpoint=str(request.url.path),
                details=aauth_inbound.audit_details(
                    None, identity=exc.identity, issuer=exc.issuer,
                    verification="failed", allowlist="not_evaluated", error=exc.code,
                ),
            )
        return _aauth_problem(exc)

    if not aauth_inbound.is_listed(verified.identity, identities):
        await platform_audit_service.log(
            event_type=AuditEventType.AUTHORIZATION, event_action="a2a_aauth_denied",
            source="a2a", actor_external_id=verified.identity, actor_ip=caller_ip,
            target_type="agent", target_id=agent_name, endpoint=str(request.url.path),
            details=aauth_inbound.audit_details(verified, allowlist="denied"),
        )
        await aauth_inbound.record_activity(agent_name, verified, allowlist="denied",
                                            error="caller not on the agent's A2A inbound allow-list")
        return JSONResponse(status_code=403,
                            content={"detail": "Caller not on the agent's A2A inbound allow-list"})

    return await _dispatch_jsonrpc(agent_name, request, raw, current_user=None, aauth=verified)


def _audit_actor(current_user: Optional[User], aauth) -> Dict[str, Any]:
    if aauth is not None:
        return {"actor_external_id": aauth.identity}
    return {"actor_user": current_user}


async def _dispatch_jsonrpc(
    agent_name: str,
    request: Request,
    raw: bytes,
    *,
    current_user: Optional[User],
    aauth: Optional["aauth_verifier.VerifiedAgent"] = None,
):
    """The JSON-RPC method table, shared by the bearer and AAuth entry points.

    Exactly one of `current_user` (bearer) / `aauth` (verified agent identity)
    is set. With `aauth` unset every line below behaves as it did before
    ent#623.
    """
    if len(raw) > _MAX_RPC_BODY_BYTES:
        return _rpc_error(None, _RPC_INVALID_REQUEST, "Request body too large")
    try:
        body = json.loads(raw)
    except Exception:
        return _rpc_error(None, _RPC_PARSE_ERROR, "Parse error: body is not valid JSON")

    if not isinstance(body, dict) or body.get("jsonrpc") != "2.0" or not isinstance(body.get("method"), str):
        return _rpc_error(body.get("id") if isinstance(body, dict) else None,
                          _RPC_INVALID_REQUEST, "Invalid JSON-RPC 2.0 request")

    method = body["method"]
    params = body.get("params") or {}
    rpc_id = body.get("id")
    if not isinstance(params, dict):
        return _rpc_error(rpc_id, _RPC_INVALID_PARAMS, "params must be an object")

    caller_ip = request.client.host if request.client else None

    # ---- message/send + message/stream ------------------------------------
    if method in ("message/send", "message/stream"):
        message = params.get("message")
        if not isinstance(message, dict):
            return _rpc_error(rpc_id, _RPC_INVALID_PARAMS, "params.message is required")
        text = _text_from_message(message)
        if not text:
            return _rpc_error(rpc_id, _RPC_INVALID_PARAMS, "message has no text parts")

        # Trigger-boundary dedup (Invariant #18): a re-delivered A2A message
        # with the same messageId must not double-execute. messageId absent →
        # dedup disabled (fail-open).
        message_id = message.get("messageId")
        decision = idempotency_service.begin(_a2a_idem_scope(agent_name, current_user, aauth), message_id)
        if decision.replay and not decision.in_flight and decision.snapshot:
            # A streaming client can't parse a bare JSON body — replay in the
            # transport it asked for.
            if method == "message/stream":
                return _replay_stream(rpc_id, decision.snapshot)
            return _rpc_result(rpc_id, decision.snapshot)
        if decision.in_flight:
            return _rpc_error(rpc_id, _RPC_INTERNAL_ERROR,
                              "A task for this messageId is already in progress", data={"retryable": True})

        if method == "message/stream":
            if aauth is not None:
                # ent#623: AAuth callers get message/send only (stated prototype scope).
                idempotency_service.fail(decision)
                return _rpc_error(rpc_id, _A2A_UNSUPPORTED,
                                  "message/stream is not supported for AAuth callers; use message/send")
            return await _stream_task(agent_name, text, current_user, rpc_id, decision, caller_ip)

        try:
            result = await _run_a2a_task(agent_name, text, current_user)
        except Exception as exc:  # noqa: BLE001 — never 5xx; A2A wants a JSON-RPC error
            idempotency_service.fail(decision)
            logger.warning("a2a message/send failed for %s: %s", agent_name, exc)
            return _rpc_error(rpc_id, _RPC_INTERNAL_ERROR, "Task execution failed")

        state = _a2a_state_for(result.status)
        task = _task_object(
            result.execution_id, state,
            text=result.response if state == "completed" else None,
            error=result.error if state == "failed" else None,
        )
        idempotency_service.complete(decision, result.execution_id, task)
        details = {"execution_id": result.execution_id, "state": state}
        if aauth is not None:
            aauth_inbound.remember_execution(result.execution_id, aauth.identity)
            details.update(aauth_inbound.audit_details(aauth, allowlist="allowed"))
            await aauth_inbound.record_activity(
                agent_name, aauth, allowlist="allowed",
                execution_id=result.execution_id, state=state,
                error=None if state == "completed" else f"task {state}",
            )
        await platform_audit_service.log(
            event_type=AuditEventType.EXECUTION, event_action="a2a_task", source="a2a",
            **_audit_actor(current_user, aauth), actor_ip=caller_ip,
            target_type="agent", target_id=agent_name,
            endpoint=str(request.url.path),
            details=details,
        )
        return _rpc_result(rpc_id, task)

    # ---- tasks/get --------------------------------------------------------
    if method == "tasks/get":
        exec_id = params.get("id")
        if not isinstance(exec_id, str) or not exec_id:
            return _rpc_error(rpc_id, _RPC_INVALID_PARAMS, "params.id is required")
        if aauth is not None and not aauth_inbound.execution_owned_by(exec_id, aauth.identity):
            return _rpc_error(rpc_id, _A2A_TASK_NOT_FOUND, "Task not found")
        row = db.get_execution(exec_id)
        # db.get_execution returns a ScheduleExecution object (not a dict) —
        # read via _exec_field so both the model and a dict work.
        if not row or _exec_field(row, "agent_name") != agent_name:
            return _rpc_error(rpc_id, _A2A_TASK_NOT_FOUND, "Task not found")
        status = _exec_field(row, "status")
        a2a_state = {
            "success": "completed", "failed": "failed", "cancelled": "canceled",
            "running": "working", "queued": "submitted",
        }.get(status, "working")
        return _rpc_result(rpc_id, _task_object(
            exec_id, a2a_state,
            text=_exec_field(row, "response") if a2a_state == "completed" else None,
            error=_exec_field(row, "error") if a2a_state == "failed" else None,
        ))

    # ---- tasks/cancel -----------------------------------------------------
    if method == "tasks/cancel":
        exec_id = params.get("id")
        if not isinstance(exec_id, str) or not exec_id:
            return _rpc_error(rpc_id, _RPC_INVALID_PARAMS, "params.id is required")
        if aauth is not None and not aauth_inbound.execution_owned_by(exec_id, aauth.identity):
            return _rpc_error(rpc_id, _A2A_TASK_NOT_FOUND, "Task not found")
        row = db.get_execution(exec_id)
        if not row or _exec_field(row, "agent_name") != agent_name:
            return _rpc_error(rpc_id, _A2A_TASK_NOT_FOUND, "Task not found")

        # Report what actually happened. Telling a caller "canceled" while the
        # task is still queued means it drains minutes later, runs, bills, and
        # performs side effects the caller believed were cancelled.
        status = _exec_field(row, "status")
        if status in ("success", "failed", "cancelled"):
            return _rpc_error(rpc_id, _A2A_TASK_NOT_CANCELABLE,
                              "Task is already in a terminal state")

        if status == "queued":
            # A queued row has no container process to signal — cancel it in the
            # backlog directly (the chat.py queued-cancel branch's shape). The
            # CAS inside cancel_queued_execution is what makes a lost race honest.
            cancelled = bool(db.cancel_queued_execution(
                exec_id, reason="Cancelled by A2A caller"))
        else:
            cancelled = bool(await terminate_execution_on_agent(agent_name, exec_id))

        if not cancelled:
            return _rpc_error(rpc_id, _A2A_TASK_NOT_CANCELABLE,
                              "Task could not be canceled")

        cancel_details = {"execution_id": exec_id}
        if aauth is not None:
            cancel_details.update(aauth_inbound.audit_details(aauth, allowlist="allowed"))
        await platform_audit_service.log(
            event_type=AuditEventType.EXECUTION, event_action="a2a_cancel", source="a2a",
            **_audit_actor(current_user, aauth), actor_ip=caller_ip,
            target_type="agent", target_id=agent_name,
            endpoint=str(request.url.path), details=cancel_details,
        )
        return _rpc_result(rpc_id, _task_object(exec_id, "canceled"))

    # ---- tasks/resubscribe (phased) --------------------------------------
    if method == "tasks/resubscribe":
        return _rpc_error(rpc_id, _A2A_UNSUPPORTED,
                          "tasks/resubscribe is not yet supported on this server")

    return _rpc_error(rpc_id, _RPC_METHOD_NOT_FOUND, f"Method not found: {method}")


def _replay_stream(rpc_id: Any, task: Dict[str, Any]) -> StreamingResponse:
    """Replay a stored task result to a `message/stream` caller in SSE.

    A streaming SDK has an event-stream parser attached; handing it a bare JSON
    body on replay breaks it. Same payload, right transport.
    """
    async def _gen():
        final = {"jsonrpc": "2.0", "id": rpc_id, "result": {**task, "final": True}}
        yield f"data: {json.dumps(final)}\n\n"

    return StreamingResponse(_gen(), media_type="text/event-stream")


async def _stream_task(agent_name: str, text: str, current_user: User,
                       rpc_id: Any, decision, caller_ip: Optional[str]) -> StreamingResponse:
    """message/stream via SSE. Emits a `working` status event, runs the task,
    then a terminal task event. Non-incremental (the agent turn is atomic), but
    spec-shaped so a streaming A2A client attaches and receives the result."""
    async def _gen():
        # Initial status: the server has accepted the task and is working.
        working = {"jsonrpc": "2.0", "id": rpc_id, "result": {
            "kind": "status-update",
            "status": {"state": "working"},
            "final": False,
        }}
        yield f"data: {json.dumps(working)}\n\n"
        try:
            result = await _run_a2a_task(agent_name, text, current_user)
        except asyncio.CancelledError:
            # A client disconnect cancels the generator, and CancelledError is a
            # BaseException (3.8+) — the `except Exception` below never sees it.
            # Without this, neither complete() nor fail() runs, the row stays
            # in_flight, and every retry with this messageId gets "already in
            # progress" for the full 24h TTL.
            idempotency_service.fail(decision)
            raise
        except Exception as exc:  # noqa: BLE001
            idempotency_service.fail(decision)
            logger.warning("a2a message/stream failed for %s: %s", agent_name, exc)
            err = {"jsonrpc": "2.0", "id": rpc_id, "error": {
                "code": _RPC_INTERNAL_ERROR, "message": "Task execution failed"}}
            yield f"data: {json.dumps(err)}\n\n"
            return
        state = _a2a_state_for(result.status)
        task = _task_object(
            result.execution_id, state,
            text=result.response if state == "completed" else None,
            error=result.error if state == "failed" else None,
        )
        idempotency_service.complete(decision, result.execution_id, task)
        await platform_audit_service.log(
            event_type=AuditEventType.EXECUTION, event_action="a2a_task_stream", source="a2a",
            actor_user=current_user, actor_ip=caller_ip,
            target_type="agent", target_id=agent_name, details={"execution_id": result.execution_id},
        )
        final = {"jsonrpc": "2.0", "id": rpc_id, "result": {**task, "final": True}}
        yield f"data: {json.dumps(final)}\n\n"

    return StreamingResponse(_gen(), media_type="text/event-stream")


# ===========================================================================
# #736 — outbound A2A calls (a Trinity agent tasks an EXTERNAL A2A agent)
# ===========================================================================
#
# Route ordering (Invariant #4) is not at risk here, and it is worth saying why
# rather than asserting it: the `/api/agents` catch-all is
# `@router.get("/{agent_name}")` — a GET, and a path parameter matches exactly
# one segment. These are POSTs with three segments, and the identical shape
# (`GET /{agent_name}/a2a/agent-card`, #737) has coexisted with that catch-all
# since Phase 1. A regression test asserts they resolve anyway, because this is
# the kind of thing a later refactor breaks silently.

#: Refusals that are the CALLER's fault (a bad reference, a registry row that
#: cannot legally be fetched) → 4xx. Everything else that went wrong out on the
#: wire is the peer's → 502/504.
_A2A_CLIENT_ERROR_STATUS = {
    "endpoint_not_https": 400,
    "endpoint_private_address": 400,
    "endpoint_dns_failure": 400,
    "endpoint_invalid": 400,
    "message_too_long": 422,
    "timeout": 504,
}


def _map_call_error(exc: A2ACallError) -> HTTPException:
    """`A2ACallError.reason` → HTTP. One mapping, used by both routes.

    Defaults to **502**, which is the honest answer for "the peer did something
    we refused or could not use" — including the case that matters most, a
    JSON-RPC error arriving on HTTP 200. Returning 200 with the peer's error
    text as if it were an answer is the silent-success path this whole feature
    has to avoid.
    """
    status_code = _A2A_CLIENT_ERROR_STATUS.get(exc.reason, 502)
    detail = {"reason": exc.reason, "message": exc.detail}
    if exc.remote_code is not None:
        detail["remote_code"] = exc.remote_code
    return HTTPException(status_code=status_code, detail=detail)


def _assert_outbound_self(current_user: User, agent_name: str) -> None:
    """An agent-scoped key may place outbound calls only AS ITSELF.

    `AuthorizedAgentByName` resolves an agent key to its OWNER and checks owner
    access, so without this a permitted sibling could place calls under a
    neighbour's name.

    Be precise about what that buys, because the obvious reading is wrong under
    the shipped OSS provider: endpoints there are **platform-scope**, so there
    is no "own" versus "neighbour" credential — every agent may name every
    registered endpoint. What this check protects is **attribution**: the
    rate-limit key, the audit row and the `agent_activities` row all name the
    agent that actually spent the call, so a sibling cannot launder its egress
    through a neighbour. It also holds the line for a future per-agent provider,
    where the obvious reading becomes the literal one — which is why it is here
    now rather than added later, after the surface has callers.

    `reject_agent_principal` is deliberately NOT used. This is a *use* of a
    capability an admin already granted by registering the endpoint, not a
    *grant* of one (the Invariant #8 line) — refusing agent principals here
    would make the feature unreachable by the only callers it exists for.
    """
    if current_user.agent_name and current_user.agent_name != agent_name:
        raise HTTPException(
            status_code=403,
            detail="An agent may only place outbound A2A calls as itself",
        )


def _require_outbound_enabled() -> None:
    """404 when the kill switch is off (§32.5 FR-11).

    404, not 403: "this capability is not present" is answered with a 404
    everywhere else in Trinity, and it keeps a disabled deployment from
    advertising a surface it will not serve.
    """
    if not a2a_outbound_service.is_outbound_enabled():
        raise HTTPException(status_code=404, detail="Not found")


@router.post("/{agent_name}/a2a/call", response_model=A2ACallResponse)
async def call_a2a_agent(
    agent_name: AuthorizedAgentByName,
    body: A2ACallRequest,
    request: Request,
    current_user: User = Depends(get_current_user),
):
    """Task an external A2A agent from `agent_name` and return its answer (#736).

    Behaviour worth knowing before you change it (§32.5 FR-18 notes):

    * **The agent container need not be running.** The call is made by the
      backend, not by the agent, so a stopped agent's owner can still drive its
      registered endpoints. That is a property of where the fetcher lives, not
      an oversight.
    * **Read-only mode and `autonomy_enabled` do not gate this.** Read-only
      governs source writes inside the container; autonomy governs whether the
      *scheduler* fires proactive work. This is a caller-initiated action.
    * **An ephemeral ghost's own key is refused**, by construction rather than
      by a check here: this route is not on the trinity-enterprise#69 fence's
      allowlist, so `_enforce_ephemeral_key_fence` 403s it at the auth entry
      point. Recorded so nobody "adds it for convenience" later — a disposable
      agent running untrusted work is the last principal that should be able to
      spend a stored credential.
    """
    _require_outbound_enabled()
    _assert_outbound_self(current_user, agent_name)

    try:
        outcome = await a2a_outbound_service.call_agent(
            agent_name=agent_name,
            endpoint_ref=body.endpoint,
            message=body.message,
            dedup_label=body.dedup_label,
            context_id=body.context_id,
            task_id=body.task_id,
            execution_id=body.execution_id,
            caller_agent_name=current_user.agent_name,
        )
    except A2AOutboundDisabled:
        raise HTTPException(status_code=404, detail="Not found")
    except A2AEndpointNotFound:
        raise HTTPException(
            status_code=404,
            detail={
                "reason": "endpoint_not_found",
                "message": (
                    "No outbound A2A endpoint is registered under that name. An "
                    "administrator registers endpoints; agents choose among them "
                    "by name."
                ),
            },
        )
    except EffectInProgressError as exc:
        raise HTTPException(status_code=409, detail=str(exc))
    except A2AAAuthRefused as exc:
        raise HTTPException(status_code=exc.status_code,
                            detail={"reason": exc.reason, "message": exc.detail})
    except A2ACallError as exc:
        raise _map_call_error(exc)

    await platform_audit_service.log(
        event_type=AuditEventType.EXECUTION,
        event_action="a2a_outbound_call",
        source="api",
        actor_user=current_user,
        actor_ip=request.client.host if request.client else None,
        target_type="agent",
        target_id=agent_name,
        endpoint=str(request.url.path),
        request_id=getattr(request.state, "request_id", None),
        details=a2a_outbound_service.audit_details(outcome),
    )

    result = outcome.result
    return A2ACallResponse(
        state=result.state,
        text=result.text,
        task_id=result.task_id,
        context_id=result.context_id,
        truncated=result.truncated,
        protocol_version=result.protocol_version,
        endpoint=outcome.endpoint_name,
        replayed=outcome.replayed,
    )


@router.post("/{agent_name}/a2a/task", response_model=A2ACallResponse)
async def get_a2a_task(
    agent_name: AuthorizedAgentByName,
    body: A2ATaskRequest,
    request: Request,
    current_user: User = Depends(get_current_user),
):
    """Poll a remote A2A task by id on a registered endpoint (#736).

    This is what makes the 30s RPC timeout safe rather than lossy: a remote that
    answers `working` hands back a `task_id`, and without a poll route that id
    would be a handle to nothing. The two are one decision.

    Deliberately NOT `effect_guard`-wrapped — a poll is a read, and deduping it
    would answer "has it finished yet?" from a cached snapshot of the last time
    it had not.
    """
    _require_outbound_enabled()
    _assert_outbound_self(current_user, agent_name)

    try:
        outcome = await a2a_outbound_service.poll_task(
            agent_name=agent_name,
            endpoint_ref=body.endpoint,
            task_id=body.task_id,
            caller_agent_name=current_user.agent_name,
        )
    except A2AOutboundDisabled:
        raise HTTPException(status_code=404, detail="Not found")
    except A2AEndpointNotFound:
        raise HTTPException(
            status_code=404,
            detail={"reason": "endpoint_not_found",
                    "message": "No outbound A2A endpoint is registered under that name."},
        )
    except A2AAAuthRefused as exc:
        raise HTTPException(status_code=exc.status_code,
                            detail={"reason": exc.reason, "message": exc.detail})
    except A2ACallError as exc:
        raise _map_call_error(exc)

    result = outcome.result
    return A2ACallResponse(
        state=result.state,
        text=result.text,
        task_id=result.task_id,
        context_id=result.context_id,
        truncated=result.truncated,
        protocol_version=result.protocol_version,
        endpoint=outcome.endpoint_name,
    )
