#: The JSON-RPC task route, the only route AAuth can authenticate (ent#623).
_A2A_RPC_PATH = "/a2a/{agent_name}"


class _A2AServerRoute(APIRoute):
    """Routes an AAuth-signed task request around the bearer dependency (ent#623).

    `POST /a2a/{name}` authenticates a bearer MCP key through
    `Depends(get_current_user)`, which 401s any request without one before the
    handler runs. An AAuth caller carries no bearer, so the dependency cannot
    simply be made conditional: FastAPI resolves every declared dependency.
    Instead, a request that carries `Signature-Key` while AAuth is live takes a
    separate entry point (`_a2a_aauth_jsonrpc`); every other request — including
    every request while the flag is off — goes through the untouched route
    handler, so the bearer path, its 401s and its dependency overrides are
    byte-identical to before. Detection keys on `Signature-Key` only: other
    RFC 9421 senders (e.g. Web Bot Auth) do not send it.

    While AAuth is live, a bearer-less 401 also advertises how to sign
    (`Accept-Signature`, `AAuth-Requirement`) — a caller discovers the scheme
    from the challenge rather than out of band.
    """

    def get_route_handler(self):
        handler = super().get_route_handler()
        if self.path != _A2A_RPC_PATH or "POST" not in (self.methods or ()):
            return handler

        async def route(request: Request):
            if "signature-key" in request.headers:
                issuer = aauth_config.active_issuer()
                if issuer:
                    return await _a2a_aauth_jsonrpc(request, issuer)
            try:
                return await handler(request)
            except HTTPException as exc:
                if (
                    exc.status_code == 401
                    and "authorization" not in request.headers
                    and aauth_config.active_issuer()
                ):
                    exc.headers = {**(exc.headers or {}), **_AAUTH_CHALLENGE_HEADERS}
                raise

        return route


# ent#157: the public A2A inbound server (well-known card + JSON-RPC task
# endpoint). Separate router (no /api prefix) so external orchestrators reach
# the spec-shaped `/a2a/{name}/.well-known/agent-card.json` + `POST /a2a/{name}`.
a2a_server_router = APIRouter(tags=["a2a-server"], route_class=_A2AServerRoute)


def _base_url_from_request(request: Request) -> str:
    """Compute the external base URL for card `url` construction.

    Order of preference:
      1. `PUBLIC_CHAT_URL` env if set — this is what external
         consumers reach Trinity through (Cloudflare tunnel, etc.).
      2. `FRONTEND_URL` env — second-best for self-hosted setups.
      3. The request's own scheme + host — works fine for clients
         that fetched the card from the same host they'll call.

    Returns "" if none of the above resolve, signalling the card
    generator to omit URL fields rather than emit a broken URL.
    """
    from config import FRONTEND_URL, PUBLIC_CHAT_URL  # local import: avoid circular at module load

    if PUBLIC_CHAT_URL:
        return PUBLIC_CHAT_URL.rstrip("/")
    if FRONTEND_URL:
        return FRONTEND_URL.rstrip("/")
    if request.url:
        return f"{request.url.scheme}://{request.url.netloc}"
    return ""


async def _fetch_template_data(agent_name: str, container) -> dict:
    """Fetch template.yaml data from the agent's container (when
    running) or fall back to docker labels (when stopped).

    Mirrors the existing `GET /api/agents/{name}/info` fallback logic
    so a stopped agent still produces a usable card. Network errors
    are logged and treated as "use the label fallback" — we never let
    a transient agent-server failure 5xx the card endpoint.
    """
    labels = container.labels or {}
    label_fallback = {
        "name": agent_name,
        "display_name": labels.get("trinity.template", agent_name),
        "description": "",
        "version": "1.0.0",
        "capabilities": [],
        "use_cases": [],
    }

    if container.status != "running":
        return label_fallback

    try:
        agent_url = f"http://agent-{agent_name}:8000/api/template/info"
        async with agent_httpx_client(agent_name, timeout=5.0) as client:
            response = await client.get(agent_url)
            if response.status_code == 200:
                data = response.json()
                # The agent-server returns `has_template=False` when
                # the agent was created without a template.yaml. Use
                # the label fallback in that case so the card still
                # advertises the agent's name + provider, just with
                # an empty skills list.
                if data.get("has_template") is False:
                    return label_fallback
                return data
            logger.info(
                f"A2A card: agent-server /api/template/info returned "
                f"{response.status_code} for {agent_name}; using label fallback"
            )
    except httpx.TimeoutException:
        logger.info(f"A2A card: agent-server timeout for {agent_name}; using label fallback")
    except Exception as e:  # noqa: BLE001 — defensive: never 5xx the card
        logger.warning(f"A2A card: agent-server unreachable for {agent_name}: {e}")

    return label_fallback


#: Hosts already warned about, so the check below costs one log line, not one
#: per card fetch.
_AAUTH_HOST_WARNED: set = set()


def _warn_issuer_card_mismatch(issuer: str, base_url: str) -> None:
    """A card served under a different host than the AAuth issuer is unusable.

    The caller signs `@authority` from the card's `url`; the callee verifies it
    against its configured issuer host. If `PUBLIC_CHAT_URL` / `FRONTEND_URL`
    and `aauth_issuer` name different hosts, every signed call fails
    `invalid_signature` and nothing says why (ent#623).
    """
    from urllib.parse import urlsplit

    card_host = (urlsplit(base_url).hostname or "").lower()
    issuer_host = aauth_config.issuer_host(issuer)
    if card_host and card_host != issuer_host and card_host not in _AAUTH_HOST_WARNED:
        _AAUTH_HOST_WARNED.add(card_host)
        logger.warning(
            "[aauth] served card host %s != aauth_issuer host %s — signed calls to "
            "this instance will fail invalid_signature until they agree "
            "(set PUBLIC_CHAT_URL to the issuer origin)", card_host, issuer_host,
        )


def _card_with_exposed_skills(
    agent_name: str,
    template_data: dict,
    base_url: str,
) -> dict:
    """Build the card, then narrow `skills[]` to what this agent may advertise.

    ent#180. THE single place a card is produced: both the authenticated
    per-agent card (#737) and the public well-known card (ent#157) go through
    here, so the two surfaces can never answer "what does this agent do?"
    differently (requirements §32.4 FR-3) and a future third surface gets the
    filter by default rather than by remembering.

    `generate_a2a_card` stays pure (no I/O) — the provider lookup lives here.
    OSS builds register no provider, so this is the identity function and the
    card is byte-identical to before ent#180.
    """
    issuer = aauth_config.active_issuer()
    if issuer and base_url:
        _warn_issuer_card_mismatch(issuer, base_url)
    card = generate_a2a_card(
        agent_name=agent_name,
        template_data=template_data,
        base_url=base_url,
        aauth_resource_metadata_url=(
            f"{issuer}/.well-known/aauth-resource.json" if issuer else None
        ),
    )
    card["skills"] = a2a_gate.filter_exposed_skills(agent_name, card.get("skills") or [])
    return card


@router.get("/{agent_name}/a2a/agent-card")
async def get_agent_card(
    agent_name: AuthorizedAgentByName,
    request: Request,
):
    """Return the A2A Agent Card (protocol `0.3.0`) for `agent_name`.

    Auth: requires `AuthorizedAgentByName` (same gate as the rest of
    the per-agent endpoints — owner, admin, or shared user). The
    issue's "public card" framing refers to the *content* of the
    card (no sensitive fields), not unauthenticated access.

    This route stays authenticated and serves ANY accessible agent. The
    unauthenticated public card is the separate, opt-in `a2a_exposed`
    surface below (`a2a_well_known_card`) — that access-policy decision
    is the exposure flag, per agent, default OFF.

    404 if the agent doesn't exist or the caller doesn't have access.
    Card generation never 5xx's — agent-server failures fall back to
    Docker labels.
    """
    container = get_agent_container(agent_name)
    if not container:
        raise HTTPException(status_code=404, detail="Agent not found")

    template_data = await _fetch_template_data(agent_name, container)
    base_url = _base_url_from_request(request)
    card = _card_with_exposed_skills(
        agent_name=agent_name,
        template_data=template_data,
        base_url=base_url,
    )
    return card


