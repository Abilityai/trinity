_FAILED_FIRST_IMPORT = _SUBPROCESS_ENV + r"""
import importlib, importlib.abc, json
fail, line, before = sys.argv[2], int(sys.argv[3]), json.loads(sys.argv[4])
# Everything `__init__` imports above the target is loaded first and the target
# is taken out of sys.modules, so no earlier statement can pull it in
# transitively: the injected ImportError fires AT the target statement, after
# every line above it (a submodule import included) has run.
import services
for name, attrs in before:
    module = importlib.import_module(name)
    for attr in attrs:
        if not hasattr(module, attr):
            importlib.import_module(f"{name}.{attr}")
saved = sys.modules.pop(fail, None)
class Refuse(importlib.abc.MetaPathFinder):
    def find_spec(self, name, path=None, target=None):
        if name == fail:
            raise ImportError("injected: " + name)
        return None
sys.meta_path.insert(0, Refuse())
try:
    import services.operator_queue_service
except ImportError as e:
    assert "injected" in str(e), e
    frames, tb = [], e.__traceback__
    while tb is not None:
        if tb.tb_frame.f_code.co_filename.endswith(os.path.join("operator_queue_service", "__init__.py")):
            frames.append(tb.tb_lineno)
        tb = tb.tb_next
    assert frames and frames[-1] == line, f"the failure fired at __init__ line {frames[-1:]}, not {line}"
else:
    raise SystemExit("the injected failure never reached the package's first import")
assert "services.operator_queue_service" not in sys.modules
sys.meta_path.pop(0)
if saved is not None:
    sys.modules[fail] = saved
import services.operator_queue_service as pkg
stale = sorted(n for n, m in list(sys.modules.items())
               if n.startswith(pkg.__name__ + ".") and getattr(m, "_oq", pkg) is not pkg)
assert not stale, stale
print("OK")
"""


def _run(script: str, *args: str):
    return subprocess.run([sys.executable, "-E", "-P", "-c", script, str(scan.BACKEND), *args],
                          capture_output=True, text=True, timeout=300, cwd=scan.REPO)


def test_a_failed_first_import_leaves_no_stale_submodule():
    """The external import `__init__` makes last fails once, at that statement,
    then the package is imported again: every submodule left loaded must hold
    the live package."""
    externals = [n for n in scan.import_time_statements(scan.parse(scan.modules()[""]))
                 if isinstance(n, ast.Import) or (isinstance(n, ast.ImportFrom) and n.level == 0)]
    last = externals[-1]
    fail = last.names[0].name if isinstance(last, ast.Import) else last.module
    before = [[a.name, []] for n in externals[:-1] if isinstance(n, ast.Import) for a in n.names]
    before += [[n.module, [a.name for a in n.names]] for n in externals[:-1] if isinstance(n, ast.ImportFrom)]
    proc = _run(_FAILED_FIRST_IMPORT, fail, str(last.lineno), json.dumps(before))
    assert proc.returncode == 0 and proc.stdout.strip().endswith("OK"), (
        f"failing {fail!r} on the first import: exit {proc.returncode}\n{proc.stderr[-3000:]}")


