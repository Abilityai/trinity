def test_every_import_time_read_is_already_defined():
    """An O1 name a submodule reads at import (a default, an annotation, a base)
    must be defined in `__init__` ABOVE that submodule's import; a sibling or
    `deps` read needs that module imported at the top of the reader."""
    init_tree = scan.parse(scan.modules()[""])
    init_defs, init_imports = scan.bindings(init_tree)
    imported_at = {}
    for node in scan.import_time_statements(init_tree):
        if isinstance(node, ast.ImportFrom) and node.level == 1:
            for sub in ([node.module] if node.module else [a.name for a in node.names]):
                imported_at.setdefault(sub, node.lineno)
    problems = []
    for mod, path in scan.modules().items():
        if not mod:
            continue
        tree = scan.parse(path)
        imports = scan.bindings(tree)[1]
        aliases = {k: v for n in scan.import_time_statements(tree) for k, v in scan.alias_targets(n, inside=True).items()}
        for line, expr in scan.import_time_exprs(tree):
            for node in ast.walk(expr):
                if not isinstance(node, ast.Attribute):
                    continue
                target = scan.resolve(node.value, aliases)
                if target == "":
                    defined = init_defs.get(node.attr, init_imports.get(node.attr))
                    if defined is None or defined >= imported_at.get(mod, float("inf")):
                        problems.append(f"{mod}.py:{line} reads _oq.{node.attr} at import, but `__init__` "
                                        f"binds it below `from . import {mod}`, or not at all")
                elif target and not target.startswith("@"):
                    local = next((k for k, v in aliases.items() if v == target), None)
                    if local is None or imports.get(local, line + 1) > line:
                        problems.append(f"{mod}.py:{line} reads {target}.{node.attr} at import before "
                                        f"importing {target}")
    assert problems == [], "; ".join(problems)


def test_a_sentinel_default_is_the_owners_object():
    """`_MARKER_UNCHANGED` is compared by identity: a default bound to a copy
    would make every write-back look like "marker due"."""
    defaults = scan.sentinel_defaults()
    if any("_MARKER_UNCHANGED = object()" in p.read_text() for p in scan.modules().values()):
        assert defaults, "_MARKER_UNCHANGED exists but no default names it — the scan went blind"
    owners = {n: mod for mod, path in scan.modules().items() for n in scan.bindings(scan.parse(path))[0]}
    for mod, qual, param, name in defaults:
        obj = _module(mod)
        for part in qual.split("."):
            obj = getattr(obj, part)
        assert inspect.signature(obj).parameters[param].default is getattr(_module(owners[name]), name), (
            f"{qual}({param}=…) is not the owner's {name}")


