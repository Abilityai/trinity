def test_no_import_time_copy_of_a_package_binding():
    """`manager = _oq._websocket_manager` at module (or class) level is a frozen
    copy: `set_websocket_manager` and every `oqs._websocket_manager` patch then
    miss its readers. Only reads at call time (or the defaults G6 sanctions)."""
    problems = []
    for mod, path in scan.modules().items():
        tree = scan.parse(path)
        aliases = {k: v for n in scan.import_time_statements(tree)
                   for k, v in scan.alias_targets(n, inside=True).items()}
        statements = list(scan.import_time_statements(tree))
        statements += [s for c in statements if isinstance(c, ast.ClassDef) for s in c.body]
        for stmt in statements:
            if not isinstance(stmt, (ast.Assign, ast.AnnAssign, ast.AugAssign)) or stmt.value is None:
                continue
            for node in ast.walk(stmt.value):
                if isinstance(node, ast.Attribute) and scan.resolve(node.value, aliases) is not None:
                    target = scan.resolve(node.value, aliases)
                    if not target.startswith("@"):
                        problems.append(f"{mod or '__init__'}.py:{stmt.lineno} binds a copy of "
                                        f"{target or '_oq'}.{node.attr} at import")
    assert problems == [], "; ".join(problems)


def test_qualified_reads_are_owner_exact():
    """`_oq.X` only for an X `__init__` defines (or owns by O1 d); `sub.X` only
    for an X `sub` defines (`deps` also by import: that is all it holds). A read
    through any other existing binding works today and detaches tomorrow, and
    `__init__` never reads its own re-export bare: that is the frozen copy."""
    owned = {}
    for mod, path in scan.modules().items():
        defs, imports = scan.bindings(scan.parse(path))
        owned[mod] = set(defs) | (set(imports) if mod == "deps" else set())
    owned[""] |= set(_PACKAGE_OWNED_IMPORTS)
    reexports = scan.reexports()
    problems = []
    for mod, path in scan.modules().items():
        where = f"{mod or '__init__'}.py"
        for node, aliases in scan.scoped(path):
            if not mod and isinstance(node, ast.Name) and isinstance(node.ctx, ast.Load) and node.id in reexports:
                problems.append(f"{where}:{node.lineno} reads the re-export `{node.id}`; "
                                f"read `{reexports[node.id]}.{node.id}`")
            if not (isinstance(node, ast.Attribute) and isinstance(node.ctx, ast.Load)):
                continue
            target = scan.resolve(node.value, aliases)
            if target is None or target.startswith("@"):
                continue
            if not target and node.attr in scan.submodules():
                problems.append(f"{where}:{node.lineno} reads the module `{node.attr}` through the package")
            elif node.attr not in owned.get(target, set()):
                problems.append(f"{where}:{node.lineno} reads {target or '_oq'}.{node.attr}, which "
                                f"`{target or '__init__'}` does not own")
    assert problems == [], "; ".join(problems)


