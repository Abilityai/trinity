def test_no_method_is_defined_on_two_classes_of_the_service():
    """A moved method left behind on the composed class shadows its mixin twin
    while every test passes on the old copy."""
    seen = {}
    for cls in _module("").OperatorQueueSyncService.__mro__:
        if cls is object:
            continue
        for name, value in vars(cls).items():
            if inspect.isfunction(value) or isinstance(value, (staticmethod, classmethod, property)):
                seen.setdefault(name, []).append(cls.__qualname__)
    doubled = {n: c for n, c in seen.items() if len(c) > 1}
    assert doubled == {}, f"defined on more than one class of the MRO: {doubled}"


