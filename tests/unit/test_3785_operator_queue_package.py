def _surface() -> dict:
    """{(target, name): [files]} over src/backend (outside the package) and tests/."""
    found = {}
    for root in (scan.BACKEND, scan.TESTS):
        for path in scan.files_naming_the_package(root):
            for key in scan.reads_through_package(path):
                found.setdefault(key, []).append(path.relative_to(scan.REPO).as_posix())
    for name in _HANDOFF_NAMES + _TEST_INCIDENTAL_NAMES:
        found.setdefault(("", name), []).append("(named in this guard)")
    return found


