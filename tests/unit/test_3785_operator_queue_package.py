"""#3785 — `services/operator_queue_service` is a package, and the split changes no behaviour.

The 2,848-line module becomes a package one slice at a time; the first slice
is the bare conversion (the whole file is `__init__.py`). Every property here
is DERIVED from the tree — never a frozen per-slice list — so the extraction
slices do not edit this file and cannot conflict on it.

The ownership model (Invariant #1(a)/(b), the PR #2487 rule):

  * O1 — `__init__` owns the config block, the rebound `_websocket_manager`,
    the #1677 budget-episode state, every name read on both sides of the
    package boundary that a test patches, and the `rate_limiter` binding.
    Submodules read them as `_oq.NAME` (`from services import
    operator_queue_service as _oq`), never a copy: one binding, so a patch on
    `oqs.NAME` reaches every reader inside and outside.
  * O2 — collaborators (`db`, `AgentClient`, …) are bound once, in `deps.py`,
    and are absent from the package: a stale `monkeypatch.setattr(oqs, "db", …)`
    raises. Tests patch `oqs.deps.X`.
  * O3 — everything else has one owner module, and siblings are read through
    the OWNING module object, never through a re-export alias.
  * O4 — every module logs as `services.operator_queue_service`.

Why this is not a style rule: a from-import freezes a binding, so a test that
patches the owner silently stops reaching that caller and nothing fails (the
git_service lesson, test_1028_*). A re-exported copy patched on the package
reaches outside readers and silently misses inside ones. These checks turn
each such detachment into a red test.
"""
