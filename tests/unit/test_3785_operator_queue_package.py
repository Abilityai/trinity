def _consumers() -> list:
    """Every src/backend module outside the package that imports it."""
    out = set()
    for path in scan.files_naming_the_package(scan.BACKEND):
        if scan.imports_the_package(path):
            parts = [p for p in path.relative_to(scan.BACKEND).with_suffix("").parts if p != "__init__"]
            out.add(".".join(parts))
    return sorted(out)


