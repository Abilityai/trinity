def test_no_from_import_between_package_modules():
    """`from . import x` (x a submodule) and `from services import
    operator_queue_service as _oq` bind MODULE objects, read at call time; any
    other from-import of the package freezes a binding — `from . import
    _websocket_manager` included, since a name that is not a submodule binds
    the package attribute. `__init__`'s re-exports are the documented exception."""
    offenders = []
    for mod, path in scan.modules().items():
        if not mod:
            continue
        for node in ast.walk(scan.parse(path)):
            if not isinstance(node, ast.ImportFrom):
                continue
            if node.level >= 1 and node.module is None and all(a.name in scan.submodules() for a in node.names):
                continue
            if node.level >= 1 or (node.module or "").startswith(scan.NAME):
                offenders.append(f"{mod}.py:{node.lineno}: from {'.' * node.level}{node.module or ''} import "
                                 + ", ".join(a.name for a in node.names))
    assert offenders == [], "from-imports between package modules freeze bindings: " + "; ".join(offenders)


