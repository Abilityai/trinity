def test_a_submodule_imports_nothing_init_has_not_already_imported():
    """`__init__` keeps the whole external import block first, so an external
    ImportError fires before any `_oq`-holding submodule has loaded. A submodule
    that imported something new at module level could fail after its siblings
    loaded, leaving them bound to a dead package object. `from services import
    docker_service` is covered only by an import of `services.docker_service`
    itself, never by `__init__` having imported `services`. Function-local
    (lazy) imports are out of scope."""
    init_tree = scan.parse(scan.modules()[""])
    first_sub = min((n.lineno for n in scan.import_time_statements(init_tree)
                     if isinstance(n, ast.ImportFrom) and n.level == 1), default=None)
    covered = scan.external_imports(init_tree, before=first_sub)
    if "deps" in scan.modules():
        covered |= scan.external_imports(scan.parse(scan.modules()["deps"]))
    problems = []
    for mod, path in scan.modules().items():
        if mod in ("", "deps"):
            continue
        for name in scan.external_imports(scan.parse(path)):
            if name == "__future__" or name.startswith(scan.NAME) or name == "services.operator_queue_service":
                continue
            parent = name.rsplit(".", 1)[0]
            if name not in covered and (parent not in covered or scan.is_backend_module(name)):
                problems.append(f"{mod}: {name}")
    assert problems == [], f"module-level imports `__init__` has not made first: {problems}"


def test_deps_loads_first_and_holds_no_package_reference():
    """`deps` is the first submodule `__init__` imports and never binds `_oq`:
    a collaborator import that fails then fails before any `_oq`-holding
    submodule has loaded, so nothing is left bound to a dead package."""
    if "deps" not in scan.modules():
        return
    first = next(n for n in scan.import_time_statements(scan.parse(scan.modules()[""]))
                 if isinstance(n, ast.ImportFrom) and n.level == 1)
    assert first.module is None and [a.name for a in first.names] == ["deps"], (
        f"__init__:{first.lineno} imports a submodule before `deps`")
    held = [n for n in ast.walk(scan.parse(scan.modules()["deps"])) if isinstance(n, (ast.Import, ast.ImportFrom))
            and "" in scan.alias_targets(n, inside=True).values()]
    assert held == [], "deps binds the package object"


def test_init_makes_every_external_import_before_its_first_submodule():
    """The order that makes a failed first import leave nothing stale: the
    external block, then `deps`, then the rest. An external import
    below the first `from . import` could fail after a submodule bound `_oq`."""
    statements = list(scan.import_time_statements(scan.parse(scan.modules()[""])))
    first_sub = next((n.lineno for n in statements if isinstance(n, ast.ImportFrom) and n.level == 1), None)
    late = [n.lineno for n in statements if first_sub is not None and n.lineno > first_sub and (
        isinstance(n, ast.Import) or (isinstance(n, ast.ImportFrom) and n.level == 0))]
    assert late == [], f"__init__ imports external modules below its first submodule import, lines {late}"


